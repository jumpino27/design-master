export function findDesignStyleById(id?: string | null): DesignStylePreset | undefined {
  if (!id) return undefined;
  return DESIGN_STYLES.find((s) => s.id === id || s.name.toLowerCase() === id.toLowerCase());
}

export function searchDesignStyles(
  query: string,
  category: string = "All"
): DesignStylePreset[] {
  const pool =
    category === "All"
      ? DESIGN_STYLES
      : DESIGN_STYLES.filter((s) => s.category === category);
  const q = query.trim().toLowerCase();
  if (!q) return pool;

  const tokens = q.split(/\s+/).filter(Boolean);
  const scored = pool
    .map((style) => {
      let score = 0;
      const nameL = style.name.toLowerCase();
      const catL = style.category.toLowerCase();
      const defL = style.definition.toLowerCase();
      const rulesL = style.visualRules.toLowerCase();
      const fitL = (style.bestFit || "").toLowerCase();
      const screensL = (style.essentialScreens || "").toLowerCase();
      const kwL = style.keywords.map((k) => k.toLowerCase());
      const moodL = style.recommendedBrand.moodTags.map((m) => m.toLowerCase());

      if (q === `#${style.number}` || q === String(style.number)) score += 500;
      if (nameL.includes(q)) score += 120;
      if (catL.includes(q)) score += 80;
      if (fitL.includes(q)) score += 70;

      let matchedAllTokens = true;
      for (const tok of tokens) {
        let tokScore = 0;
        if (`#${style.number}` === tok || String(style.number) === tok) tokScore += 100;
        if (nameL.includes(tok)) tokScore += 40;
        if (catL.includes(tok)) tokScore += 30;
        if (kwL.some((k) => k.includes(tok))) tokScore += 35;
        if (moodL.some((m) => m.includes(tok))) tokScore += 25;
        if (fitL.includes(tok)) tokScore += 28;
        if (screensL.includes(tok)) tokScore += 18;
        if (defL.includes(tok)) tokScore += 15;
        if (rulesL.includes(tok)) tokScore += 10;
        if (tokScore === 0) {
          matchedAllTokens = false;
        }
        score += tokScore;
      }

      if (!matchedAllTokens && tokens.length > 1) {
        score = Math.floor(score * 0.35);
      }
      return { style, score };
    })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score || a.style.number - b.style.number);

  return scored.map((item) => item.style);
}

export function buildCombinedStyleBrief(
  style: DesignStylePreset,
  selectedModifierIds: string[] = []
): string {
  const mods = DESIGN_STYLE_MODIFIERS.filter((m) => selectedModifierIds.includes(m.id));
  const modNames = mods.map((m) => m.term.toLowerCase());
  const comboLabel = [style.name.toLowerCase(), ...modNames].join(" + ");
  const modDescriptions = mods.map((m) => `${m.term} (${m.description})`).join("; ");
  const fitAndScreens = [
    style.bestFit ? `Best fit: ${style.bestFit}` : "",
    style.essentialScreens ? `Essential screens/components: ${style.essentialScreens}` : "",
  ]
    .filter(Boolean)
    .join(" ");
  const base = `Style brief: "${ mods.length > 0 ? comboLabel : style.name.toLowerCase() }". Primary style #${style.number} ${style.name} (${style.category}): ${style.definition} Visual rules (apply using the User's Brand Kit colors, logo & typography): ${style.visualRules}${fitAndScreens ? ` ${fitAndScreens}` : ""}`;
  return mods.length > 0 ? `${base} Combined with modifiers: ${modDescriptions}` : base;
}
